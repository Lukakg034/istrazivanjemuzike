"""Merge all research CSVs into a master index and regenerate statistics.

Usage:
    python tools/build_master_index.py

Outputs:
    exports/master_index.csv          all records, UTF-8 with BOM (opens correctly in Excel)
    reports/database_statistics.md    counts by file, country, genre, tradition, decade,
                                      verification status, plus data-quality issues
"""

import csv
import json
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from schema import (  # noqa: E402
    ATTRIBUTION_TYPE,
    COLUMNS,
    EXPORTS_DIR,
    FILE_LABELS,
    FILE_PREFIXES,
    MUSICAL_TRADITION,
    PIANO_VERSION_EXISTS,
    REPORTS_DIR,
    RESEARCH_DIR,
    ROOT,
    VERIFICATION_STATUS,
    duplicate_key,
    normalise_key,
)


def load_all() -> tuple[list[dict], list[str]]:
    records, issues = [], []
    for csv_name in FILE_PREFIXES:
        path = RESEARCH_DIR / csv_name
        if not path.exists():
            issues.append(f"`{csv_name}` is missing")
            continue
        with path.open(encoding="utf-8-sig", newline="") as handle:
            reader = csv.DictReader(handle)
            if reader.fieldnames != COLUMNS:
                issues.append(f"`{csv_name}` header does not match the schema")
            for row in reader:
                row["source_file"] = csv_name
                records.append(row)
    return records, issues


def find_issues(records: list[dict]) -> list[str]:
    issues = []
    ids = Counter(row["id"] for row in records)
    for record_id, count in ids.items():
        if count > 1:
            issues.append(f"ID `{record_id}` is used {count} times")

    by_key = defaultdict(list)
    for row in records:
        by_key[duplicate_key(row)].append(row["id"])
    for ids_for_key in by_key.values():
        if len(ids_for_key) > 1:
            issues.append(f"Duplicate title + artist: {', '.join(ids_for_key)}")

    vocab_checks = [
        ("verification_status", VERIFICATION_STATUS),
        ("musical_tradition", MUSICAL_TRADITION),
        ("attribution_type", ATTRIBUTION_TYPE),
        ("piano_version_exists", PIANO_VERSION_EXISTS),
    ]
    for row in records:
        if not row.get("source_url"):
            issues.append(f"`{row['id']}` has no source_url")
        for field, vocabulary in vocab_checks:
            if row.get(field) not in vocabulary:
                issues.append(f"`{row['id']}` has invalid {field} {row.get(field)!r}")
    return issues


def possible_title_collisions(records: list[dict]) -> list[str]:
    """Same title, different artist, different file: often legitimate, worth a glance."""
    by_title = defaultdict(list)
    for row in records:
        title = normalise_key(row["title_original"])
        if len(title) >= 4:
            by_title[title].append(row)
    lines = []
    for rows in by_title.values():
        files = {row["source_file"] for row in rows}
        if len(rows) > 1 and len(files) > 1:
            described = "; ".join(f"{row['id']} ({row['artist'] or row['composer']})" for row in rows)
            lines.append(f"\"{rows[0]['title_original']}\": {described}")
    return sorted(lines)


def table(header: tuple[str, ...], rows: list[tuple]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def counter_table(label: str, counter: Counter, limit: int | None = None) -> str:
    items = counter.most_common(limit)
    return table((label, "Records"), [(name or "(empty)", count) for name, count in items])


def write_statistics(records: list[dict], issues: list[str]) -> Path:
    per_file = []
    for csv_name, prefix in FILE_PREFIXES.items():
        rows = [row for row in records if row["source_file"] == csv_name]
        status = Counter(row["verification_status"] for row in rows)
        countries = {row["country"] for row in rows if row["country"]}
        per_file.append((
            f"`{csv_name}`", prefix, len(rows), len(countries),
            status["Verified"], status["Partially verified"], status["Unverified"],
        ))

    countries = Counter()
    for row in records:
        for country in row["country"].split("|"):
            countries[country.strip()] += 1

    sections = [
        "# Database statistics",
        "",
        f"Generated by `tools/build_master_index.py` on {datetime.now():%Y-%m-%d %H:%M}. "
        "Do not edit by hand; rerun the script instead.",
        "",
        f"**Total records:** {len(records)}  ",
        f"**Countries / cultural areas represented:** {len(countries)}  ",
        f"**Distinct genres:** {len({row['genre'] for row in records if row['genre']})}  ",
        f"**Distinct artists/composers:** {len({normalise_key(row['artist'] or row['composer']) for row in records})}",
        "",
        "## Records per research file",
        "",
        table(("File", "Prefix", "Records", "Countries", "Verified", "Partially verified", "Unverified"), per_file),
        "",
        "## Verification status",
        "",
        counter_table("Status", Counter(row["verification_status"] for row in records)),
        "",
        "## Musical tradition",
        "",
        counter_table("Tradition", Counter(row["musical_tradition"] for row in records)),
        "",
        "## Attribution type",
        "",
        counter_table("Attribution", Counter(row["attribution_type"] for row in records)),
        "",
        "## Decade",
        "",
        counter_table("Decade", Counter(row["decade"] for row in records)),
        "",
        "## Existing piano version",
        "",
        counter_table("piano_version_exists", Counter(row["piano_version_exists"] for row in records)),
        "",
        "## Countries",
        "",
        counter_table("Country", countries),
        "",
        "## Genres",
        "",
        counter_table("Genre", Counter(row["genre"] for row in records)),
        "",
        "## Data-quality issues",
        "",
        "\n".join(f"- {issue}" for issue in issues) if issues else "None found.",
        "",
        "## Same title in different files (review manually; usually different songs)",
        "",
        "\n".join(f"- {line}" for line in possible_title_collisions(records)) or "None found.",
        "",
    ]
    path = REPORTS_DIR / "database_statistics.md"
    path.write_text("\n".join(sections), encoding="utf-8")
    return path


def write_explorer_data(records: list[dict]) -> Path:
    """Write docs/data.js so the static explorer works on GitHub Pages and as a local file."""
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    payload = {
        "generated": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "file_labels": FILE_LABELS,
        "records": records,
    }
    path = docs / "data.js"
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    path.write_text(f"window.TONELAB = {body};\n", encoding="utf-8")
    return path


def write_master_index(records: list[dict]) -> Path:
    EXPORTS_DIR.mkdir(exist_ok=True)
    path = EXPORTS_DIR / "master_index.csv"
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=COLUMNS + ["source_file"], quoting=csv.QUOTE_ALL)
        writer.writeheader()
        writer.writerows(records)
    return path


def main() -> None:
    records, issues = load_all()
    issues += find_issues(records)
    index_path = write_master_index(records)
    stats_path = write_statistics(records, issues)
    explorer_path = write_explorer_data(records)
    print(f"{len(records)} records -> {index_path.relative_to(index_path.parents[1])}")
    print(f"Statistics -> {stats_path.relative_to(stats_path.parents[1])}")
    print(f"Explorer data -> {explorer_path.relative_to(explorer_path.parents[1])}")
    print(f"{len(issues)} data-quality issues")


if __name__ == "__main__":
    main()
